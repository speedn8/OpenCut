import { _electron as electron } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
const root=process.cwd();
const evidence=path.resolve(root,'../../../../desktop-evidence');
await fs.mkdir(evidence,{recursive:true});
const app=await electron.launch({executablePath:path.join(root,'node_modules/electron/dist/electron.exe'),args:[root],env:{...process.env,OPENCUT_STUDIO_DATA_DIR:path.join(evidence,'test-profile')},timeout:30000});
const page=await app.firstWindow();
const errors=[];
page.on('pageerror',e=>errors.push(e.stack));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.waitForLoadState('networkidle');
await page.screenshot({path:path.join(evidence,'01-library.png')});
console.log(JSON.stringify({url:page.url(),body:await page.locator('body').innerText(),errors},null,2));
await page.getByRole('button',{name:'New project',exact:true}).click();
await page.waitForTimeout(3000);
console.log(JSON.stringify({url:page.url(),body:await page.locator('body').innerText(),buttons:await page.getByRole('button').evaluateAll(es=>es.map(e=>({text:e.textContent,label:e.getAttribute('aria-label'),title:e.getAttribute('title')}))),errors},null,2));
await page.screenshot({path:path.join(evidence,'02-empty-editor.png')});
await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].close());
await app.process().exitCode===null ? new Promise(resolve=>app.process().once('exit',resolve)) : undefined;
console.log('PROBE_COMPLETE');
